"""Run reproducible local Kessel latency benchmarks and write report artifacts."""

from __future__ import annotations

import argparse
import csv
import json
import math
import os
import statistics
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from kessel_gateway.user_config import UserConfig


EFFORTS = ("low", "medium", "high", "xhigh")
CASES = (
    ("codex", "fresh"),
    ("codex", "warm"),
    ("claude", "fresh"),
)
PROMPT = "Reply with exactly BENCHMARK_OK."


def percentile(values: list[float], probability: float) -> float:
    ordered = sorted(values)
    index = max(0, math.ceil(probability * len(ordered)) - 1)
    return ordered[index]


def run_once(
    base_url: str,
    provider: str,
    backend: str,
    effort: str,
    api_key: str,
) -> dict:
    payload = json.dumps(
        {
            "model": "default",
            "backend": backend,
            "reasoning_effort": effort,
            "stream": True,
            "messages": [{"role": "user", "content": PROMPT}],
        }
    ).encode()
    request = urllib.request.Request(
        f"{base_url}/v1/{provider}/chat/completions",
        data=payload,
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    started = time.perf_counter()
    first_token_ms = None
    output = ""
    with urllib.request.urlopen(request, timeout=600) as response:
        for raw_line in response:
            line = raw_line.decode("utf-8", errors="replace").strip()
            if not line.startswith("data: ") or line == "data: [DONE]":
                continue
            event = json.loads(line[6:])
            if "error" in event:
                raise RuntimeError(event["error"].get("message", "stream failed"))
            choices = event.get("choices", [])
            if not choices:
                continue
            text = choices[0].get("delta", {}).get("content", "")
            if text:
                first_token_ms = first_token_ms or (time.perf_counter() - started) * 1000
                output += text
    total_ms = (time.perf_counter() - started) * 1000
    if not output.strip():
        raise RuntimeError("benchmark received no text")
    return {
        "provider": provider,
        "backend": backend,
        "effort": effort,
        "ttft_ms": round(first_token_ms or total_ms, 2),
        "total_ms": round(total_ms, 2),
    }


def summarize(samples: list[dict]) -> list[dict]:
    rows = []
    for provider, backend in CASES:
        for effort in EFFORTS:
            selected = [
                sample
                for sample in samples
                if sample["provider"] == provider
                and sample["backend"] == backend
                and sample["effort"] == effort
            ]
            totals = [sample["total_ms"] for sample in selected]
            first_tokens = [sample["ttft_ms"] for sample in selected]
            rows.append(
                {
                    "provider": provider,
                    "backend": backend,
                    "effort": effort,
                    "runs": len(selected),
                    "ttft_p50_ms": round(statistics.median(first_tokens), 1),
                    "ttft_p95_ms": round(percentile(first_tokens, 0.95), 1),
                    "total_p50_ms": round(statistics.median(totals), 1),
                    "total_p95_ms": round(percentile(totals, 0.95), 1),
                }
            )
    return rows


def write_markdown(rows: list[dict], path: Path) -> None:
    lines = [
        "<!-- Generated by benchmarks/run.py. -->",
        "| Provider | Backend | Effort | Runs | TTFT p50 | TTFT p95 | Total p50 | Total p95 |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        lines.append(
            "| {provider} | {backend} | {effort} | {runs} | {ttft_p50_ms:.0f} ms | "
            "{ttft_p95_ms:.0f} ms | {total_p50_ms:.0f} ms | {total_p95_ms:.0f} ms |".format(
                **row
            )
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_chart(rows: list[dict], path: Path) -> None:
    width, height = 1100, 430
    margin_left, margin_bottom, margin_top = 70, 100, 30
    plot_height = height - margin_bottom - margin_top
    maximum = max(row["total_p95_ms"] for row in rows) or 1
    bar_width = 58
    gap = 22
    elements = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#f4f6f4"/>',
        '<style>text{font-family:Segoe UI,sans-serif;fill:#18201b}.label{font-size:11px}.value{font-size:10px}</style>',
        f'<line x1="{margin_left}" y1="{margin_top + plot_height}" x2="{width - 20}" y2="{margin_top + plot_height}" stroke="#58645c"/>',
    ]
    for index, row in enumerate(rows):
        x = margin_left + 15 + index * (bar_width + gap)
        bar_height = row["total_p50_ms"] / maximum * plot_height
        y = margin_top + plot_height - bar_height
        color = "#146b45" if row["backend"] == "warm" else "#6b8f7a"
        elements.append(
            f'<rect x="{x}" y="{y:.1f}" width="{bar_width}" height="{bar_height:.1f}" rx="4" fill="{color}"/>'
        )
        elements.append(
            f'<text class="value" x="{x + bar_width / 2}" y="{y - 5:.1f}" text-anchor="middle">{row["total_p50_ms"]:.0f}</text>'
        )
        label = f'{row["provider"]} {row["backend"]} {row["effort"]}'
        elements.append(
            f'<text class="label" transform="translate({x + 12},{height - margin_bottom + 12}) rotate(55)">{label}</text>'
        )
    elements.append(
        '<text x="16" y="20" font-size="13">Median end-to-end latency (ms)</text>'
    )
    elements.append("</svg>")
    path.write_text("\n".join(elements), encoding="utf-8")


def update_readme_table(rows: list[dict], readme: Path) -> None:
    if not readme.exists():
        return
    start_marker = "<!-- benchmark-table:start -->"
    end_marker = "<!-- benchmark-table:end -->"
    text = readme.read_text(encoding="utf-8")
    if start_marker not in text or end_marker not in text:
        return
    table_path = readme.parent / "benchmarks" / "results.md"
    table = table_path.read_text(encoding="utf-8").splitlines()[1:]
    replacement = start_marker + "\n" + "\n".join(table) + "\n" + end_marker
    before, remainder = text.split(start_marker, 1)
    _, after = remainder.split(end_marker, 1)
    readme.write_text(before + replacement + after, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://127.0.0.1:4880")
    parser.add_argument("--runs", type=int, default=5)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).parent)
    parser.add_argument(
        "--api-key",
        help="Kessel API key; defaults to KESSEL_API_KEY or the saved config",
    )
    args = parser.parse_args()
    if args.runs < 1:
        parser.error("--runs must be at least 1")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    api_key = args.api_key or os.getenv("KESSEL_API_KEY") or UserConfig.load().api_key
    if not api_key:
        parser.error("no Kessel API key found; run kessel setup or pass --api-key")

    # Start the persistent server before measured warm samples.
    run_once(args.base_url, "codex", "warm", "low", api_key)

    samples = []
    for provider, backend in CASES:
        for effort in EFFORTS:
            for run_number in range(1, args.runs + 1):
                sample = run_once(
                    args.base_url, provider, backend, effort, api_key
                )
                sample["run"] = run_number
                samples.append(sample)
                print(
                    provider,
                    backend,
                    effort,
                    run_number,
                    f'{sample["total_ms"]:.0f}ms',
                )

    rows = summarize(samples)
    (args.output_dir / "results.json").write_text(
        json.dumps({"samples": samples, "summary": rows}, indent=2) + "\n",
        encoding="utf-8",
    )
    with (args.output_dir / "results.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=samples[0].keys())
        writer.writeheader()
        writer.writerows(samples)
    write_markdown(rows, args.output_dir / "results.md")
    write_chart(rows, args.output_dir / "latency.svg")
    update_readme_table(rows, Path(__file__).resolve().parents[1] / "README.md")


if __name__ == "__main__":
    main()
